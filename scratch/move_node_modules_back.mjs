import fs from 'node:fs';
import path from 'node:path';

const backupDir = 'C:\\Users\\dell\\Desktop\\coaching_node_modules_backup';

const dirs = [
  'node_modules',
  'backend/node_modules',
  'frontend/node_modules',
  'backend/uploads'
];

dirs.forEach(d => {
  const destPath = path.join(backupDir, d.replace(/\//g, '_'));
  if (fs.existsSync(destPath)) {
    const originalPath = path.resolve(d);
    if (fs.existsSync(originalPath)) {
      fs.rmSync(originalPath, { recursive: true, force: true });
    }
    fs.renameSync(destPath, originalPath);
    console.log(`Restored ${d} from backup`);
  } else {
    console.log(`Backup for ${d} does not exist`);
  }
});
