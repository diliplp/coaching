import fs from 'node:fs';
import path from 'node:path';

const dirs = [
  'node_modules',
  'backend/node_modules',
  'frontend/node_modules'
];

dirs.forEach(d => {
  const tmpPath = path.resolve(d + '_tmp');
  if (fs.existsSync(tmpPath)) {
    const originalPath = path.resolve(d);
    fs.renameSync(tmpPath, originalPath);
    console.log(`Restored ${d}_tmp to ${d}`);
  } else {
    console.log(`${d}_tmp does not exist`);
  }
});
