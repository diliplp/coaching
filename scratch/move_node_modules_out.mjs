import fs from 'node:fs';
import path from 'node:path';

const backupDir = 'C:\\Users\\dell\\Desktop\\coaching_node_modules_backup';
if (!fs.existsSync(backupDir)) {
  fs.mkdirSync(backupDir, { recursive: true });
}

const dirs = [
  'node_modules',
  'backend/node_modules',
  'frontend/node_modules',
  'backend/uploads'
];

dirs.forEach(d => {
  const fullPath = path.resolve(d);
  if (fs.existsSync(fullPath)) {
    const destPath = path.join(backupDir, d.replace(/\//g, '_'));
    if (fs.existsSync(destPath)) {
      // Clean up previous backup if exists
      fs.rmSync(destPath, { recursive: true, force: true });
    }
    fs.renameSync(fullPath, destPath);
    console.log(`Moved ${d} to ${destPath}`);
  } else {
    console.log(`${d} does not exist`);
  }
});
